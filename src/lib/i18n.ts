const LANG_KEY = 'garut_journey_lang_v1'
const LANG_EVENT = 'garut_journey_lang_updated'

export function getCurrentLanguage(): LanguageCode {
  if (typeof window === 'undefined') return 'id'
  try {
    const saved = localStorage.getItem(LANG_KEY) as LanguageCode
    if (saved && (saved === 'id' || saved === 'en' || saved === 'ja' || saved === 'ar')) {
      return saved
    }
  } catch {}
  // Check admin site settings default
  try {
    const raw = localStorage.getItem('garut_journey_site_settings_v1')
    if (raw) {
      const parsed = JSON.parse(raw)
      if (parsed.siteLanguage && ['id', 'en', 'ja', 'ar'].includes(parsed.siteLanguage)) {
        return parsed.siteLanguage
      }
    }
  } catch {}
  return 'id'
}

export function setLanguage(lang: LanguageCode) {
  if (typeof window === 'undefined') return
  try {
    localStorage.setItem(LANG_KEY, lang)
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: lang }))
  } catch (err) {
    console.error('Failed to set language:', err)
  }
}

export function useLanguage() {
  const [lang, setLangState] = useState<LanguageCode>('id')

  useEffect(() => {
    const current = getCurrentLanguage()
    setLangState(current)
    document.documentElement.lang = current
    document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr'

    const handler = (e: Event) => {
      const customEvent = e as CustomEvent<LanguageCode>
      if (customEvent.detail) {
        setLangState(customEvent.detail)
      } else {
        setLangState(getCurrentLanguage())
      }
    }

    // Also listen to site settings update if admin changes default language
    const settingsHandler = () => {
      // If consumer hasn't set an explicit preference, adopt admin setting
      const consumerChoice = localStorage.getItem(LANG_KEY)
      if (!consumerChoice) {
        setLangState(getCurrentLanguage())
      }
    }

    window.addEventListener(LANG_EVENT, handler)
    window.addEventListener('garut_settings_updated', settingsHandler)
    window.addEventListener('storage', handler)
    return () => {
      window.removeEventListener(LANG_EVENT, handler)
      window.removeEventListener('garut_settings_updated', settingsHandler)
      window.removeEventListener('storage', handler)
    }
  }, [])

  const switchLanguage = (newLang: LanguageCode) => {
    setLanguage(newLang)
    setLangState(newLang)
  }

  const t = translations[lang] || translations.id

  return {
    lang,
    t,
    switchLanguage,
    supportedLanguages: SUPPORTED_LANGUAGES,
    isRtl: lang === 'ar',
  }
}
